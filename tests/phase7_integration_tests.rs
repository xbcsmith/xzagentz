#[test]
fn test_end_to_end_plan_generation_with_real_components() {
    let parser = MarkdownArchitectureParser::new();
    let generator = MockPlanGenerator::new();
    let writer = MarkdownPlanWriter::new();

    let arch_content = r#"# Microservices Architecture

## Overview

A scalable microservices architecture for handling high-volume traffic.

## Components

### API Gateway
Entry point for all client requests.

### Authentication Service
Handles user authentication and authorization.

### Data Processing Service
Processes incoming data streams.

## Requirements

- REQ-001: Support 10,000 concurrent users
- REQ-002: 99.9% uptime SLA
- REQ-003: Data encryption at rest and in transit
"#;

    let arch_doc = parser.parse(arch_content).unwrap();

    // Generate plan
    let options = PlanOptions::default().with_num_phases(3);
    let result = generator.generate_plan(&arch_doc, &options);
    assert!(result.is_ok());

    let plan = result.unwrap();
    assert!(!plan.phases().is_empty());

    // Save plan
    let temp_dir = TempDir::new().unwrap();
    let output_path = temp_dir.path().join("implementation_plan.md");
    let save_result = writer.write_plan(&plan, &output_path);
    assert!(save_result.is_ok());

    // Verify output file
    assert!(output_path.exists());
    let content = fs::read_to_string(&output_path).unwrap();
    assert!(content.contains("Implementation Plan"));
}

