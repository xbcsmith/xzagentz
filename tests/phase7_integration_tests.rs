struct MockPlanGenerator {
    should_fail: bool,
}

impl MockPlanGenerator {
    fn new() -> Self {
        Self { should_fail: false }
    }

    fn with_failure() -> Self {
        Self { should_fail: true }
    }
}

impl PlanGenerator for MockPlanGenerator {
    type Error = std::io::Error;

    fn generate_plan(
        &self,
        _arch: &ArchitectureDocument,
        _options: &PlanOptions,
    ) -> Result<xzagentz::domain::planning::Plan, Self::Error> {
        if self.should_fail {
            return Err(std::io::Error::new(
                std::io::ErrorKind::Other,
                "Mock generation failed",
            ));
        }

        let metadata =
            PlanMetadata::new(chrono::Utc::now(), "mock-model", PathBuf::from("test.md"));

        let task1 = Task::new("Setup infrastructure", "Configure the infrastructure")
            .with_acceptance_criteria(vec!["Infrastructure configured".to_string()])
            .with_components(vec!["Infrastructure".to_string()]);

        let phase1 = Phase::new("phase-1", "Infrastructure Setup", "Setup infrastructure")
            .with_tasks(vec![task1])
            .with_estimated_duration("1 week");

        let task2 = Task::new("Implement features", "Build core features")
            .with_acceptance_criteria(vec!["Features implemented".to_string()])
            .with_components(vec!["Core".to_string()]);

        let phase2 = Phase::new("phase-2", "Feature Development", "Develop features")
            .with_tasks(vec![task2])
            .with_estimated_duration("2 weeks");

        Ok(xzagentz::domain::planning::Plan::new(
            "Mock Implementation Plan",
            "Generated by mock",
            vec![phase1, phase2],
            metadata,
        ))
    }
}

struct MockArchitectureParser {
    should_fail: bool,
}

impl MockArchitectureParser {
    fn new() -> Self {
        Self { should_fail: false }
    }

    fn with_failure() -> Self {
        Self { should_fail: true }
    }
}

impl ArchitectureParser for MockArchitectureParser {
    type Error = std::io::Error;

    fn parse(&self, _content: &str) -> Result<ArchitectureDocument, Self::Error> {
        if self.should_fail {
            return Err(std::io::Error::new(
                std::io::ErrorKind::NotFound,
                "Mock parse failed",
            ));
        }

        let mut doc = ArchitectureDocument::new("Mock Architecture")
            .with_description("A mock architecture document");

        let section = Section::new("Overview", 1).with_content("Mock overview content");
        doc.add_section(section);

        let component = Component::new("MockComponent", "mock-comp")
            .with_description("A mock component")
            .with_technology("Service");
        doc.add_component(component);

        let requirement = Requirement::new("REQ-001", "Mock requirement")
            .with_priority("High")
            .with_category("Functional");
        doc.add_requirement(requirement);

        Ok(doc)
    }
}

struct MockPlanWriter {
    should_fail: bool,
}

impl MockPlanWriter {
    fn new() -> Self {
        Self { should_fail: false }
    }

    fn with_failure() -> Self {
        Self { should_fail: true }
    }
}

impl PlanWriter for MockPlanWriter {
    type Error = std::io::Error;

    fn write_plan(
        &self,
        _plan: &xzagentz::domain::planning::Plan,
        _output_path: &Path,
    ) -> Result<(), Self::Error> {
        if self.should_fail {
            return Err(std::io::Error::new(
                std::io::ErrorKind::PermissionDenied,
                "Mock write failed",
            ));
        }
        Ok(())
    }
}

// Wrapper for MockArchitectureParser that reads files
struct MockFileParser {
    inner: MockArchitectureParser,
}

impl MockFileParser {
    fn new() -> Self {
        Self {
            inner: MockArchitectureParser::new(),
        }
    }

    fn with_failure() -> Self {
        Self {
            inner: MockArchitectureParser::with_failure(),
        }
    }

    fn parse_file(&self, path: &Path) -> Result<ArchitectureDocument, std::io::Error> {
        let content = fs::read_to_string(path)?;
        self.inner.parse(&content)
    }
}

