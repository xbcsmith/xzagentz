#[test]
fn test_multiple_plan_generations() {
    let generator = MockPlanGenerator::new();
    let parser = MockArchitectureParser::new();
    let writer = MarkdownPlanWriter::new();

    let arch_doc = parser.parse("# Test Architecture\n\nContent").unwrap();

    let temp_dir = TempDir::new().unwrap();

    for i in 0..5 {
        let output_path = temp_dir.path().join(format!("plan_{}.md", i));
        let options = PlanOptions::default();

        let result = generator.generate_plan(&arch_doc, &options);
        assert!(result.is_ok());

        let plan = result.unwrap();
        let save_result = writer.write_plan(&plan, &output_path);
        assert!(save_result.is_ok());
        assert!(output_path.exists());
    }
}

